async function runReconciliation() {
    const bankFile = document.getElementById('bankCsvInput').files[0];
    const glFile = document.getElementById('glCsvInput').files[0];

    if (!bankFile || !glFile) {
        alert("Please select both Bank Statement and General Ledger CSV files!");
        return;
    }

    const bankText = await bankFile.text();
    const glText = await glFile.text();

    // 1. Write uploaded files to Emscripten MEMFS
    Module.FS.writeFile('/bank_feed.csv', bankText);
    Module.FS.writeFile('/general_ledger.csv', glText);

    // 2. Execute C++ Engine Process
    const bankPathPtr = Module.allocateUTF8('/bank_feed.csv');
    const glPathPtr = Module.allocateUTF8('/general_ledger.csv');

    const status = Module._processFilesFromMEMFS(bankPathPtr, glPathPtr);

    if (status === 0) {
        // Read Stats from C++ Engine
        document.getElementById('statProcessed').innerText = Module._getTotalProcessed();
        document.getElementById('statMatched').innerText = Module._getTotalMatched();
        document.getElementById('statUnmatched').innerText = Module._getTotalUnmatched() + 
            ` (Heap Size: ${Module._getDiscrepancyQueueSize()})`;

        document.getElementById('results').style.display = 'block';
    } else {
        alert("Error executing C++ File Handling Engine. Status Code: " + status);
    }
}

// Custom Trie Prefix Checking function
function checkVendorPrefix() {
    const prefix = document.getElementById('prefixInput').value.trim();
    const badge = document.getElementById('trieResult');

    if (prefix.length === 0) {
        badge.innerText = "Awaiting Input...";
        badge.className = "badge";
        return;
    }

    const prefixPtr = Module.allocateUTF8(prefix);
    const exists = Module._searchVendorPrefix(prefixPtr);

    if (exists === 1) {
        badge.innerText = "Match Found in Trie ✓";
        badge.className = "badge found";
    } else {
        badge.innerText = "No Prefix Match ✗";
        badge.className = "badge not-found";
    }
}

// Download Audit Trail CSV generated by std::ofstream
function downloadReport() {
    const reportData = Module.FS.readFile('/reconciliation_report.csv', { encoding: 'utf8' });
    const blob = new Blob([reportData], { type: 'text/csv' });
    const url = window.URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'reconciliation_report.csv';
    a.click();
}